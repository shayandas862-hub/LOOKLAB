#!/usr/bin/env node
// Regenerates src/ui/views/*.view.tsx and the design CSS from design/*.dc.html.
// Logic files (src/ui/logic/*.logic.tsx) are written only when missing: after the
// first port they are owned code and never overwritten (D-LL-014).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { convertTemplate } from './port-design/convert.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCREENS = [
  ['Look Lab.dc.html', 'Shell'],
  ['Projects.dc.html', 'Projects'],
  ['Breakdown.dc.html', 'Breakdown'],
  ['LocationKit.dc.html', 'LocationKit'],
  ['SetPlan.dc.html', 'SetPlan'],
  ['Shots.dc.html', 'Shots'],
  ['MoodBoard.dc.html', 'MoodBoard'],
  ['SetSheet.dc.html', 'SetSheet'],
  ['Library.dc.html', 'Library'],
  ['Activity.dc.html', 'Activity'],
  ['Settings.dc.html', 'Settings'],
];

const views = join(ROOT, 'src/ui/views');
const logic = join(ROOT, 'src/ui/logic');
mkdirSync(views, { recursive: true });
mkdirSync(logic, { recursive: true });

const header = (file) =>
  `// GENERATED by scripts/port-design.mjs from design/${file}.\n// Do not edit. Change the design or the converter, then run \`npm run port-design\`.\n`;

// Owned file: design literals that screens replace with real data as they are wired.
const bindingsPath = join(ROOT, 'src/ui/bindings.json');
const bindings = existsSync(bindingsPath) ? JSON.parse(readFileSync(bindingsPath, 'utf8')) : {};

const cssBlocks = new Set();
const written = { views: 0, logicNew: 0, logicKept: 0 };

for (const [file, name] of SCREENS) {
  const html = readFileSync(join(ROOT, 'design', file), 'utf8');
  const r = convertTemplate(html, name, bindings[name] ?? {});
  writeFileSync(join(views, `${name}.view.tsx`), header(file) + r.tsx);
  written.views++;
  for (const block of r.css.split('\n')) if (block.trim()) cssBlocks.add(block.trim());

  const logicPath = join(logic, `${name}.logic.tsx`);
  if (existsSync(logicPath)) {
    written.logicKept++;
    continue;
  }
  const body = r.script.replace(/class Component extends DCLogic/, `export class ${name} extends DCLogic`);
  writeFileSync(
    logicPath,
    `// @ts-nocheck: behaviour ported from design/${file}; typed as each screen is wired to real actions.\n` +
      `// Owned code (D-LL-014): the port wrote this once and will not overwrite it.\n` +
      `import React from 'react';\nimport { DCLogic } from '../runtime/dc';\nimport { ${name}View, defaults } from '../views/${name}.view';\n` +
      body.trimEnd() +
      `\n\n${name}.view = ${name}View;\n${name}.defaultProps = defaults;\n`,
  );
  written.logicNew++;
}

writeFileSync(
  join(views, 'design.generated.css'),
  `/* GENERATED by scripts/port-design.mjs from design/*.dc.html. Do not edit. */\n${[...cssBlocks].join('\n')}\n`,
);
writeFileSync(
  join(logic, 'screens.ts'),
  header('*.dc.html') +
    SCREENS.filter(([, n]) => n !== 'Shell').map(([, n]) => `export { ${n} } from './${n}.logic';`).join('\n') +
    '\n',
);
console.log(`views written: ${written.views} · logic created: ${written.logicNew} · logic kept: ${written.logicKept} · css rules: ${cssBlocks.size}`);
